-- ============================================================================
-- 修复 seed 过程检孤儿（quality/process 关联审计发现）
--
-- 现象：qc_inspection(source_type='process_card') 的 10 条种子记录 source_no =
--       PC20240501001..PC20240510001，但其对应的 prd_process_card 行被软删
--       (deleted = 1)。process 页检验弹窗按 pc.deleted = 0 关联，故这些种子
--       检验记录在生产 UI 不可见 → 跨系统关联断裂。
--
-- 修复：将这 10 张种子流程卡恢复为未删除（deleted = 0），使其与种子检验记录
--       关联可见。
--
-- 幂等：仅作用于 deleted = 1 的行；以 card_no 为锚（不依赖 id），可重复安全执行。
-- 前置已校验：上述 card_no 在 deleted = 0 中无重复，不会触发 uk_card_no 唯一键冲突。
-- ============================================================================

UPDATE prd_process_card
SET deleted = 0,
    update_time = NOW()
WHERE deleted = 1
  AND card_no IN (
    'PC20240501001','PC20240502001','PC20240503001','PC20240504001','PC20240505001',
    'PC20240506001','PC20240507001','PC20240508001','PC20240509001','PC20240510001'
  );
