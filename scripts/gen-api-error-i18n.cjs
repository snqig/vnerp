#!/usr/bin/env node
/**
 * 生成 src/lib/api-error-i18n.ts（P1-2 路由级核心数据）。
 * 数据源：scripts/api-errors-report.json 的 uniqueErrMsgs（API 路由去重错误消息）。
 * 产出：
 *   - API_MESSAGE_TO_CODE: 中文消息 -> AE#### 错误码（供 errorResponse 查码）
 *   - API_ERROR_MESSAGES:  AE#### 错误码 -> 中文消息（供前端译员翻译）
 * 确定性：按出现文件数降序编号，幂等可重跑。
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = process.cwd();
const report = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts', 'api-errors-report.json'), 'utf8'));

// 仅取错误消息（已在 scan 中按 ERR_RE 分类），按文件数降序编号，常见错误得小号
const errs = [...(report.uniqueErrMsgs || [])].sort((a, b) => b.files.length - a.files.length);

const msgToCode = {};
const codeToMsg = {};
errs.forEach((e, i) => {
  const code = 'AE' + String(i + 1).padStart(4, '0');
  // 去重保护：若同一消息重复出现，保持首次编号
  if (!msgToCode[e.msg]) {
    msgToCode[e.msg] = code;
    codeToMsg[code] = e.msg;
  }
});

const header = `// AUTO-GENERATED by scripts/gen-api-error-i18n.cjs — 勿手改。
// P1-2 路由级：API 错误消息 i18n 映射。
//   errorResponse 按中文消息查 API_MESSAGE_TO_CODE 得 errorCode；
//   前端译员按 errorCode 在 API_ERROR_MESSAGES 中取当前语言消息。
//   规范来源为 zh-CN；en/vi/zh-TW 暂回退后端 message（与 Error 命名空间一致）。
`;

const content =
  header +
  `export const API_MESSAGE_TO_CODE: Record<string, string> = ${JSON.stringify(msgToCode, null, 2)};\n\n` +
  `export const API_ERROR_MESSAGES: Record<string, string> = ${JSON.stringify(codeToMsg, null, 2)};\n\n` +
  `/** 供 IntlProvider 合并进译员：code -> 当前语言消息（zh-CN 规范来源）。 */\n` +
  `export function getApiErrorMessage(code: string): string | null {\n  return API_ERROR_MESSAGES[code] ?? null;\n}\n`;

const outPath = path.join(ROOT, 'src', 'lib', 'api-error-i18n.ts');
fs.writeFileSync(outPath, content, 'utf8');

console.log(`✅ 已生成 ${outPath}`);
console.log(`   错误消息总数(去重): ${errs.length}`);
console.log(`   实际生成 code 数: ${Object.keys(codeToMsg).length}`);
console.log(`   首 5 条:`, errs.slice(0, 5).map((e) => `${msgToCode[e.msg]}=${e.msg}`).join(' | '));
